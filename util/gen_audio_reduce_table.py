#!/usr/bin/env python3
"""Generate the half-band decimator taps for the audio stream reducer.

The reducer (audio_reduce.c) decimates by 2 through a linear-phase half-band
FIR and cascades two stages for a divisor of 4. A half-band kernel has its
cutoff at a quarter of the input rate, every second tap equal to zero apart
from the centre, and the odd-offset taps symmetric about the centre.

Design:
  * 59 taps (4k + 3, so both end taps are non-zero), Kaiser beta 9.0
  * passband flat (+-0.0003 dB) to 0.20 * fs_in, which is 0.40 * fs_out
  * stop-band >= 90 dB from 0.30 * fs_in (0.60 * fs_out), the first input
    frequency that aliases onto the 0.40 * fs_out passband edge
  * Q30 taps, tap sum exactly 2^30 (unity DC gain), int64 accumulation at
    run time

Regenerate:  python util/gen_audio_reduce_table.py
"""

import math
import os
import sys

TAPS = 59
BETA = 9.0
Q = 30


def bessel_i0(x):
    """Modified Bessel function of the first kind, order 0 (series)."""
    total = 1.0
    term = 1.0
    k = 0
    while True:
        k += 1
        term *= (x / (2.0 * k)) ** 2
        total += term
        if term < 1e-18 * total or k > 200:
            return total


def sinc(x):
    if x == 0.0:
        return 1.0
    return math.sin(math.pi * x) / (math.pi * x)


def design():
    """Return (centre, sides) as Q30 integers.

    sides[i] is the tap at offset +-(2 * i + 1) from the centre.
    """
    m = (TAPS - 1) // 2
    window_norm = bessel_i0(BETA)
    raw = {}
    for off in range(1, m + 1, 2):
        win = bessel_i0(BETA * math.sqrt(1.0 - (off / m) ** 2)) / window_norm
        raw[off] = 0.5 * sinc(off / 2.0) * win
    total = 0.5 + 2.0 * sum(raw.values())
    scale = 1.0 / total
    sides = [int(round(raw[off] * scale * (1 << Q)))
             for off in range(1, m + 1, 2)]
    centre = (1 << Q) - 2 * sum(sides)
    return centre, sides


def main():
    centre, sides = design()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                       "ZZ9000_proto.sdk", "ZZ9000OS", "src",
                       "audio_reduce_table.h")
    with open(out, "w", newline="\n") as f:
        f.write("/*\n")
        f.write(" * Generated by util/gen_audio_reduce_table.py -- DO NOT EDIT.\n")
        f.write(" *\n")
        f.write(" * Regenerate with: python util/gen_audio_reduce_table.py\n")
        f.write(" * Half-band decimate-by-2 kernel: %d taps, Kaiser beta %g,\n"
                % (TAPS, BETA))
        f.write(" * Q%d, tap sum exactly 2^%d. Tap offsets +-1, +-3, ... +-%d\n"
                % (Q, Q, TAPS // 2))
        f.write(" * from the centre carry the audio_reduce_side values below;\n")
        f.write(" * every other off-centre tap is zero.\n")
        f.write(" *\n")
        f.write(" * SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write(" */\n\n")
        f.write("#ifndef AUDIO_REDUCE_TABLE_H\n")
        f.write("#define AUDIO_REDUCE_TABLE_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("#define AUDIO_REDUCE_TAPS %dU\n" % TAPS)
        f.write("#define AUDIO_REDUCE_SIDES %dU\n" % len(sides))
        f.write("#define AUDIO_REDUCE_Q %d\n" % Q)
        f.write("#define AUDIO_REDUCE_CENTRE %d\n\n" % centre)
        f.write("static const int32_t audio_reduce_side[AUDIO_REDUCE_SIDES] = {\n")
        for i in range(0, len(sides), 5):
            f.write("\t" + ", ".join("%d" % v for v in sides[i:i + 5]) + ",\n")
        f.write("};\n\n")
        f.write("#endif /* AUDIO_REDUCE_TABLE_H */\n")
    sys.stderr.write("wrote %s (centre %d, %d side taps)\n"
                     % (out, centre, len(sides)))


if __name__ == "__main__":
    main()
