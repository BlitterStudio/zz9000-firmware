static int dominant_red(const uint8_t *pixel)
{
	return pixel[0] < 64U && pixel[1] < 64U &&
	       pixel[2] > 200U && pixel[3] == 0xff;
}

static int dominant_red_rgb888(const uint8_t *pixel)
{
	return pixel[0] > 200U && pixel[1] < 64U && pixel[2] < 64U;
}

static int dominant_green_rgb888(const uint8_t *pixel)
{
	return pixel[0] < 64U && pixel[1] > 200U && pixel[2] < 64U;
}

static int dominant_blue_rgb888(const uint8_t *pixel)
{
	return pixel[0] < 64U && pixel[1] < 64U && pixel[2] > 200U;
}

static int near_white_rgb888(const uint8_t *pixel)
{
	return pixel[0] > 200U && pixel[1] > 200U && pixel[2] > 200U;
}

static int dominant_green(const uint8_t *pixel)
{
	return pixel[0] < 64U && pixel[1] > 200U &&
	       pixel[2] < 64U && pixel[3] == 0xff;
}

static int dominant_blue(const uint8_t *pixel)
{
	return pixel[0] > 200U && pixel[1] < 64U &&
	       pixel[2] < 64U && pixel[3] == 0xff;
}

static int near_white(const uint8_t *pixel)
{
	return pixel[0] > 200U && pixel[1] > 200U &&
	       pixel[2] > 200U && pixel[3] == 0xff;
}

int main(void)
{
	uint8_t dst[4U * 4U * 4U];
	uint8_t rgb[4U * 4U * 3U];
	uint32_t width = 0;
	uint32_t height = 0;
	uint32_t bytes_written = 0;
	uint32_t backend_flags;

	if (strcmp(sdk_jpeg_backend_name(), "libjpeg-turbo") != 0) {
		printf("unexpected JPEG backend '%s'\n", sdk_jpeg_backend_name());
		return 8;
	}

	backend_flags = sdk_jpeg_backend_flags();
	if ((backend_flags & SDK_JPEG_BACKEND_FLAG_BASELINE) == 0U) {
		printf("JPEG backend did not advertise baseline support\n");
		return 9;
	}
	if ((backend_flags & SDK_JPEG_BACKEND_FLAG_PROGRESSIVE) == 0U) {
		printf("libjpeg-turbo did not advertise progressive support\n");
		return 10;
	}
	if ((backend_flags & SDK_JPEG_BACKEND_FLAG_DIRECT_BGRA) == 0U) {
		printf("libjpeg-turbo did not advertise direct BGRA output\n");
		return 11;
	}
	if ((backend_flags & SDK_JPEG_BACKEND_FLAG_DIRECT_RGB888) == 0U) {
		printf("libjpeg-turbo did not advertise direct RGB888 output\n");
		return 17;
	}
	if ((backend_flags & SDK_JPEG_BACKEND_FLAG_SCALING) == 0U) {
		printf("libjpeg-turbo did not advertise decode-time scaling\n");
		return 15;
	}
	if ((sdk_jpeg_service_flags() &
	     SDK_SERVICE_FLAG_IMAGE_JPEG_BASELINE) == 0U) {
		printf("JPEG service flags did not advertise baseline JPEG\n");
		return 12;
	}
	if ((sdk_jpeg_service_flags() &
	     SDK_SERVICE_FLAG_IMAGE_JPEG_PROGRESSIVE) == 0U) {
		printf("JPEG service flags did not advertise progressive JPEG\n");
		return 13;
	}
	if ((sdk_jpeg_service_flags() &
	     SDK_SERVICE_FLAG_IMAGE_JPEG_DIRECT_BGRA) == 0U) {
		printf("JPEG service flags did not advertise direct BGRA\n");
		return 14;
	}
	if ((sdk_jpeg_service_flags() &
	     SDK_SERVICE_FLAG_IMAGE_JPEG_SCALING) == 0U) {
		printf("JPEG service flags did not advertise decode-time scaling\n");
		return 16;
	}
	if ((sdk_jpeg_service_flags() &
	     SDK_SERVICE_FLAG_IMAGE_RGB888_OUTPUT) == 0U) {
		printf("JPEG service flags did not advertise RGB888 output\n");
		return 18;
	}

	memset(dst, 0, sizeof(dst));
	if (!sdk_jpeg_decode_to_surface(jpeg_2x2, sizeof(jpeg_2x2),
	                                dst, 4U, 4U, 16U,
	                                SDK_SURFACE_FORMAT_BGRA8888,
	                                1U, 1U,
	                                &width, &height, &bytes_written)) {
		printf("jpeg decode failed\n");
		return 1;
	}

	if (width != 2U || height != 2U || bytes_written != 16U) {
		printf("unexpected metadata %u x %u bytes=%u\n",
		       width, height, bytes_written);
		return 2;
	}

	if (!dominant_red(&dst[(1U * 16U) + (1U * 4U)])) {
		printf("top-left pixel was not red-dominant\n");
		return 3;
	}
	if (!dominant_green(&dst[(1U * 16U) + (2U * 4U)])) {
		printf("top-right pixel was not green-dominant\n");
		return 4;
	}
	if (!dominant_blue(&dst[(2U * 16U) + (1U * 4U)])) {
		printf("bottom-left pixel was not blue-dominant\n");
		return 5;
	}
	if (!near_white(&dst[(2U * 16U) + (2U * 4U)])) {
		printf("bottom-right pixel was not white\n");
		return 6;
	}

	if (sdk_jpeg_decode_to_surface(jpeg_2x2, sizeof(jpeg_2x2),
	                               dst, 1U, 1U, 4U,
	                               SDK_SURFACE_FORMAT_BGRA8888,
	                               0U, 0U,
	                               &width, &height, &bytes_written)) {
		printf("decode unexpectedly fit into too-small destination\n");
		return 7;
	}

	memset(rgb, 0, sizeof(rgb));
	if (!sdk_jpeg_decode_to_surface(jpeg_2x2, sizeof(jpeg_2x2),
	                                rgb, 4U, 4U, 12U,
	                                SDK_SURFACE_FORMAT_RGB888,
	                                1U, 1U,
	                                &width, &height, &bytes_written)) {
		printf("jpeg RGB888 decode failed\n");
		return 19;
	}
	if (width != 2U || height != 2U || bytes_written != 12U) {
		printf("unexpected RGB888 metadata %u x %u bytes=%u\n",
		       width, height, bytes_written);
		return 20;
	}
	if (!dominant_red_rgb888(&rgb[(1U * 12U) + (1U * 3U)])) {
		printf("RGB888 top-left pixel was not red-dominant\n");
		return 21;
	}

	return 0;
}
