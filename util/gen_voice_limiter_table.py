#!/usr/bin/env python3
"""Emit the voice limiter table, or check its marked block with --check.

Integer nodes of the rational soft knee, 256 equal segments per octave of
8191 + (magnitude - 24576). The last node covers every supported wide sum.
SPDX-License-Identifier: GPL-3.0-or-later
"""
import argparse
from pathlib import Path
import sys

BEGIN = "/* BEGIN GENERATED VOICE LIMITER TABLE */"
END = "/* END GENERATED VOICE LIMITER TABLE */"


def generate():
    values = []
    for octave in range(16):
        for segment in range(256):
            x = (8192 + segment * 32) << octave
            values.append(32767 - (8191 * 8191 + x - 1) // x)
    x = 1 << 29
    values.append(32767 - (8191 * 8191 + x - 1) // x)
    lines = [BEGIN, "/* Generated by util/gen_voice_limiter_table.py; do not edit. */",
             "static const uint16_t voice_limiter_table[4097] = {"]
    for i in range(0, len(values), 12):
        lines.append("\t" + ", ".join(str(v) for v in values[i:i + 12]) + ",")
    return "\n".join(lines + ["};", END]) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", type=Path, metavar="SOURCE")
    args = parser.parse_args()
    expected = generate()
    if args.check is None:
        sys.stdout.write(expected)
        return 0
    source = args.check.read_text(encoding="utf-8")
    start = source.index(BEGIN)
    end = source.index(END, start) + len(END)
    if source[start:end] + "\n" != expected:
        print(f"{args.check}: voice limiter table differs", file=sys.stderr)
        return 1
    print(f"{args.check}: voice limiter table is reproducible")
    return 0


if __name__ == "__main__":
    sys.exit(main())
