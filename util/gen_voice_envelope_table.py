#!/usr/bin/env python3
"""Emit the voice envelope table, or check its marked block with --check.

voice_envelope_table[j] = round(2^(31 - j/256)) for j = 0..256, the Q31 value
of 2^(-j/256). The engine splits an attenuation in octaves (Q24) into whole
octaves (a shift), a table index and a 16-bit interpolation fraction. The
values are computed with Decimal so the output does not depend on the
platform's libm.
SPDX-License-Identifier: GPL-3.0-or-later
"""
import argparse
from decimal import ROUND_HALF_EVEN, Decimal, getcontext
from pathlib import Path
import sys

BEGIN = "/* BEGIN GENERATED VOICE ENVELOPE TABLE */"
END = "/* END GENERATED VOICE ENVELOPE TABLE */"


def generate():
    getcontext().prec = 60
    two = Decimal(2)
    values = []
    for j in range(257):
        value = two ** (Decimal(31) - Decimal(j) / Decimal(256))
        values.append(int(value.quantize(Decimal(1), rounding=ROUND_HALF_EVEN)))
    lines = [BEGIN, "/* Generated by util/gen_voice_envelope_table.py; do not edit. */",
             "static const uint32_t voice_envelope_table[257] = {"]
    for i in range(0, len(values), 6):
        lines.append("\t" + ", ".join(f"{v}U" for v in values[i:i + 6]) + ",")
    return "\n".join(lines + ["};", END]) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", type=Path, metavar="SOURCE")
    args = parser.parse_args()
    expected = generate()
    if args.check is None:
        sys.stdout.write(expected)
        return 0
    source = args.check.read_text(encoding="utf-8")
    start = source.index(BEGIN)
    end = source.index(END, start) + len(END)
    if source[start:end] + "\n" != expected:
        print(f"{args.check}: voice envelope table differs", file=sys.stderr)
        return 1
    print(f"{args.check}: voice envelope table is reproducible")
    return 0


if __name__ == "__main__":
    sys.exit(main())
