static int expect_digest(const char *label, const uint8_t *actual,
                         const uint8_t *expected, uint32_t length)
{
	uint32_t i;

	for (i = 0; i < length; i++) {
		if (actual[i] != expected[i]) {
			printf("%s: digest mismatch at byte %u\n", label, i);
			printf("%s: actual", label);
			for (i = 0; i < length; i++)
				printf(" %02x", actual[i]);
			printf("\n%s: expected", label);
			for (i = 0; i < length; i++)
				printf(" %02x", expected[i]);
			printf("\n");
			return 0;
		}
	}

	return 1;
}

static int expect_bytes(const char *label, const uint8_t *actual,
                        const uint8_t *expected, uint32_t length)
{
	uint32_t i;

	for (i = 0; i < length; i++) {
		if (actual[i] != expected[i]) {
			printf("%s: mismatch at byte %u\n", label, i);
			return 0;
		}
	}

	return 1;
}

