	memset(chacha_roundtrip, 0, sizeof(chacha_roundtrip));
	sdk_chacha20_xor(chacha_key, chacha_nonce, 1U,
	                 chacha_cipher, chacha_roundtrip,
	                 sizeof(chacha_roundtrip));
