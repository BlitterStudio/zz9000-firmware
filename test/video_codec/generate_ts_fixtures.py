# Generate the small MPEG Transport Stream test fixtures and their Program
# Stream twins. Each twin pair is muxed from the same encode, so a demuxer
# must produce the same elementary streams from both:
# - MPEG-2 video + MP2 audio: Program Stream, Transport Stream, M2TS (the
#   Transport Stream with a 4-byte timestamp before each packet)
# - MPEG-1 video + MP2 audio: Program Stream, Transport Stream
# - MPEG-2 video + two MP2 audio tracks: Program Stream, Transport Stream
#
# Generator: FFmpeg 7.1.5-0+deb13u1 (Debian trixie) + Python 3.13, run in a
# container:
#   docker run --rm -v <repo>:/src zz9-ffmpeg-fixtures:local \
#     python3 /src/test/video_codec/generate_ts_fixtures.py

import os
import subprocess
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))

VIDEO = ["-f", "lavfi", "-i", "testsrc=size=96x64:rate=25:duration=0.2"]
AUDIO_1K = ["-f", "lavfi", "-i",
            "sine=frequency=1000:sample_rate=48000:duration=0.2"]
AUDIO_440 = ["-f", "lavfi", "-i",
             "sine=frequency=440:sample_rate=48000:duration=0.2"]
ENCODE = ["-pix_fmt", "yuv420p", "-g", "5", "-b:v", "200k",
          "-c:a", "mp2", "-b:a", "96k", "-ar", "48000", "-ac", "2",
          "-bitexact"]


def write_c_include(path, symbol_name, data):
    with open(path, "w", newline="\n") as f:
        f.write("/* Generated by generate_ts_fixtures.py. */\n")
        f.write(f"static const uint8_t {symbol_name}[] = {{\n")
        for i in range(0, len(data), 12):
            chunk = data[i:i + 12]
            f.write("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
        f.write("};\n")
        f.write(f"static const uint32_t {symbol_name}_len = {len(data)}U;\n")
    print(f"Wrote {path} ({len(data)} bytes)")


def mux(tmpdir, name, inputs, maps, codec, muxer, extra=()):
    out = os.path.join(tmpdir, name)
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y"]
    for item in inputs:
        cmd += item
    cmd += maps
    cmd += ["-c:v", codec] + ENCODE + ["-f", muxer] + list(extra) + [out]
    subprocess.run(cmd, check=True)
    with open(out, "rb") as f:
        return f.read()


def to_m2ts(ts):
    """M2TS: each 188-byte packet behind a 4-byte TP_extra_header (copy
    permission 0, 30-bit arrival time stamp). ffmpeg's own M2TS mode types
    MP2 audio as private data (stream_type 0x06), which no player of this
    kind reads, so the prefix is added here to the Transport Stream."""
    out = bytearray()
    for n in range(len(ts) // 188):
        out += (n * 0x1b0).to_bytes(4, "big")
        out += ts[n * 188:(n + 1) * 188]
    return bytes(out)


def emit(tmpdir, base, inputs, maps, codec, outputs):
    for suffix, muxer, extra in outputs:
        if muxer == "m2ts":
            data = to_m2ts(mux(tmpdir, base + "_m2ts_source.ts", inputs, maps,
                               codec, "mpegts", extra))
        else:
            data = mux(tmpdir, base + suffix, inputs, maps, codec, muxer,
                       extra)
        write_c_include(
            os.path.join(HERE, f"ts_{base}_{suffix.lstrip('.')}_fixture.inc"),
            f"zz9k_ts_{base}_{suffix.lstrip('.')}_fixture", data)


def build_fixtures():
    with tempfile.TemporaryDirectory() as tmpdir:
        one = [VIDEO, AUDIO_1K]
        emit(tmpdir, "mpeg2", one, [], "mpeg2video",
             [(".ps", "mpeg", ()),
              (".ts", "mpegts", ()),
              (".m2ts", "m2ts", ())])
        emit(tmpdir, "mpeg1", one, [], "mpeg1video",
             [(".ps", "mpeg", ()),
              (".ts", "mpegts", ())])
        two = [VIDEO, AUDIO_1K, AUDIO_440]
        emit(tmpdir, "mpeg2_2a", two,
             ["-map", "0:v", "-map", "1:a", "-map", "2:a"], "mpeg2video",
             [(".ps", "mpeg", ()),
              (".ts", "mpegts", ())])


if __name__ == "__main__":
    build_fixtures()
