/*
 * The voice constants exist twice: in the SDK's zz9k/voice.h (what clients
 * build against) and in the firmware's audio_voice.h and audio_voice_session.h
 * (what the engine and the session use). This file includes both and fails to
 * compile when any op, flag, limit, feature bit, state or status offset
 * differs between them.
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 */

#include <stdio.h>

#include "audio_voice.h"
#include "audio_voice_session.h"
#include "zz9k/voice.h"

#define PARITY(name, sdk, fw) \
	typedef char parity_##name[((sdk) == (fw)) ? 1 : -1]

/* Engine records. */
PARITY(op_start, ZZ9K_VOICE_OP_START, AUDIO_VOICE_OP_START);
PARITY(op_loop, ZZ9K_VOICE_OP_LOOP, AUDIO_VOICE_OP_LOOP);
PARITY(op_set, ZZ9K_VOICE_OP_SET, AUDIO_VOICE_OP_SET);
PARITY(op_stop, ZZ9K_VOICE_OP_STOP, AUDIO_VOICE_OP_STOP);
PARITY(op_master, ZZ9K_VOICE_OP_MASTER, AUDIO_VOICE_OP_MASTER);
PARITY(op_direction, ZZ9K_VOICE_OP_DIRECTION, AUDIO_VOICE_OP_DIRECTION);
PARITY(op_mode, ZZ9K_VOICE_OP_MODE, AUDIO_VOICE_OP_MODE);
PARITY(op_envelope, ZZ9K_VOICE_OP_ENVELOPE, AUDIO_VOICE_OP_ENVELOPE);
PARITY(op_config, ZZ9K_VOICE_OP_CONFIG, AUDIO_VOICE_OP_CONFIG);
PARITY(set_rate, ZZ9K_VOICE_SET_RATE, AUDIO_VOICE_SET_RATE);
PARITY(set_volume, ZZ9K_VOICE_SET_VOLUME, AUDIO_VOICE_SET_VOLUME);
PARITY(set_rate_hz, ZZ9K_VOICE_SET_RATE_HZ, AUDIO_VOICE_RATE_HZ);
PARITY(dir_backward, ZZ9K_VOICE_DIR_BACKWARD, AUDIO_VOICE_DIR_BACKWARD);
PARITY(config_ramp, ZZ9K_VOICE_CONFIG_RAMP, AUDIO_VOICE_CONFIG_RAMP);
PARITY(config_limiter, ZZ9K_VOICE_CONFIG_LIMITER, AUDIO_VOICE_CONFIG_LIMITER);
PARITY(config_interp, ZZ9K_VOICE_CONFIG_INTERP, AUDIO_VOICE_CONFIG_INTERP);
PARITY(config_known,
       ZZ9K_VOICE_CONFIG_RAMP | ZZ9K_VOICE_CONFIG_LIMITER |
       ZZ9K_VOICE_CONFIG_INTERP,
       AUDIO_VOICE_CONFIG_KNOWN);
PARITY(mode_interp, ZZ9K_VOICE_MODE_INTERP, AUDIO_VOICE_MODE_INTERP);
PARITY(mode_known, ZZ9K_VOICE_MODE_INTERP, AUDIO_VOICE_MODE_KNOWN);
PARITY(stop_release, ZZ9K_VOICE_STOP_RELEASE, AUDIO_VOICE_STOP_RELEASE);
PARITY(env_set, ZZ9K_VOICE_ENVELOPE_SET, AUDIO_VOICE_ENV_SET);
PARITY(env_known, ZZ9K_VOICE_ENVELOPE_SET, AUDIO_VOICE_ENV_KNOWN);
PARITY(env_step_frames, ZZ9K_VOICE_ENVELOPE_STEP_FRAMES,
       AUDIO_VOICE_ENV_STEP_FRAMES);
PARITY(env_steps_per_ms, ZZ9K_VOICE_ENVELOPE_STEPS_PER_MS,
       AUDIO_VOICE_ENV_STEPS_PER_MS);
PARITY(env_ms_max, ZZ9K_VOICE_ENVELOPE_MS_MAX, AUDIO_VOICE_ENV_MS_MAX);
PARITY(env_sustain_unity, ZZ9K_VOICE_ENVELOPE_SUSTAIN_UNITY,
       AUDIO_VOICE_ENV_SUSTAIN_UNITY);
/* A step is 16 frames and a millisecond is 48 frames of the output rate. */
PARITY(env_steps_are_a_ms, ZZ9K_VOICE_ENVELOPE_STEP_FRAMES *
       ZZ9K_VOICE_ENVELOPE_STEPS_PER_MS * 1000U, ZZ9K_VOICE_OUTPUT_RATE);
PARITY(interp_inherit, ZZ9K_VOICE_INTERP_INHERIT,
       AUDIO_VOICE_INTERP_MODE_INHERIT);
PARITY(interp_nearest, ZZ9K_VOICE_INTERP_NEAREST,
       AUDIO_VOICE_INTERP_MODE_NEAREST);
PARITY(interp_linear, ZZ9K_VOICE_INTERP_LINEAR, AUDIO_VOICE_INTERP_MODE_LINEAR);
PARITY(interp_cubic, ZZ9K_VOICE_INTERP_CUBIC, AUDIO_VOICE_INTERP_MODE_CUBIC);
/* A wire selector is the engine's session value plus one. */
PARITY(interp_nearest_value, ZZ9K_VOICE_INTERP_NEAREST,
       AUDIO_VOICE_INTERP_NEAREST + 1U);
PARITY(interp_linear_value, ZZ9K_VOICE_INTERP_LINEAR,
       AUDIO_VOICE_INTERP_LINEAR + 1U);
PARITY(interp_cubic_value, ZZ9K_VOICE_INTERP_CUBIC,
       AUDIO_VOICE_INTERP_CUBIC + 1U);
PARITY(ramp_max, ZZ9K_VOICE_RAMP_MAX_FRAMES, AUDIO_VOICE_RAMP_MAX_FRAMES);
PARITY(fade_slots, ZZ9K_VOICE_FADE_SLOTS, AUDIO_VOICE_FADE_SLOTS);
PARITY(master_unity, ZZ9K_VOICE_MASTER_UNITY, AUDIO_VOICE_MASTER_UNITY);
PARITY(max_voices, ZZ9K_VOICE_MAX_VOICES, AUDIO_VOICE_MAX_VOICES);
PARITY(max_samples, ZZ9K_VOICE_MAX_SAMPLES, AUDIO_VOICE_MAX_SAMPLES);
PARITY(output_rate, ZZ9K_VOICE_OUTPUT_RATE, AUDIO_VOICE_OUT_HZ);
PARITY(rate_max, ZZ9K_VOICE_RATE_MAX_HZ, AUDIO_VOICE_MAX_HZ);
PARITY(fmt_s8, ZZ9K_VOICE_FORMAT_S8, AUDIO_VOICE_FMT_S8);
PARITY(fmt_s16, ZZ9K_VOICE_FORMAT_S16, AUDIO_VOICE_FMT_S16);
PARITY(fmt_s8s, ZZ9K_VOICE_FORMAT_S8S, AUDIO_VOICE_FMT_S8S);
PARITY(fmt_s16s, ZZ9K_VOICE_FORMAT_S16S, AUDIO_VOICE_FMT_S16S);
PARITY(fmt_count, ZZ9K_VOICE_FORMAT_COUNT, AUDIO_VOICE_FMT_COUNT);

/* Session: open flags, ring, status block, states, bank. */
PARITY(open_ntsc, ZZ9K_VOICE_OPEN_FLAG_NTSC, AUDIO_VOICE_OPEN_NTSC);
PARITY(open_linear, ZZ9K_VOICE_OPEN_FLAG_LINEAR, AUDIO_VOICE_OPEN_LINEAR);
PARITY(open_low_latency, ZZ9K_VOICE_OPEN_FLAG_LOW_LATENCY,
       AUDIO_VOICE_OPEN_LOW_LATENCY);
PARITY(open_known, ZZ9K_VOICE_OPEN_FLAG_KNOWN, AUDIO_VOICE_OPEN_KNOWN);
PARITY(upload_copy, ZZ9K_VOICE_UPLOAD_FLAG_COPY, AUDIO_VOICE_UPLOAD_COPY);
PARITY(upload_define, ZZ9K_VOICE_UPLOAD_FLAG_DEFINE, AUDIO_VOICE_UPLOAD_DEFINE);
PARITY(upload_known, ZZ9K_VOICE_UPLOAD_FLAG_KNOWN, AUDIO_VOICE_UPLOAD_KNOWN);
PARITY(ring_header, ZZ9K_VOICE_RING_HEADER_BYTES, AUDIO_VOICE_RING_HEADER_BYTES);
PARITY(ring_record, ZZ9K_VOICE_RECORD_BYTES, AUDIO_VOICE_RING_RECORD_BYTES);
PARITY(ring_min, ZZ9K_VOICE_RING_MIN_RECORDS, AUDIO_VOICE_RING_MIN_RECORDS);
PARITY(ring_max, ZZ9K_VOICE_RING_MAX_RECORDS, AUDIO_VOICE_RING_MAX_RECORDS);
PARITY(ring_write, ZZ9K_VOICE_RING_WRITE_CURSOR_OFFSET, AUDIO_VOICE_RING_OFF_WRITE);
PARITY(ring_heartbeat, ZZ9K_VOICE_RING_HEARTBEAT_OFFSET,
       AUDIO_VOICE_RING_OFF_HEARTBEAT);
PARITY(bank_max, ZZ9K_VOICE_BANK_MAX_BYTES, AUDIO_VOICE_BANK_MAX_BYTES);
PARITY(status_bytes, ZZ9K_VOICE_STATUS_BYTES, AUDIO_VOICE_STATUS_BYTES);
PARITY(state_closed, ZZ9K_VOICE_STATE_CLOSED, AUDIO_VOICE_STATE_CLOSED);
PARITY(state_open, ZZ9K_VOICE_STATE_OPEN, AUDIO_VOICE_STATE_OPEN);
PARITY(state_live, ZZ9K_VOICE_STATE_LIVE, AUDIO_VOICE_STATE_LIVE);
PARITY(margin_none, ZZ9K_VOICE_JITTER_NONE, AUDIO_VOICE_STATUS_MARGIN_NONE);

/* Status block offsets. */
PARITY(off_playing, ZZ9K_VOICE_STATUS_PLAYING_FRAME_OFFSET,
       AUDIO_VOICE_STATUS_OFF_PLAYING);
PARITY(off_horizon, ZZ9K_VOICE_STATUS_HORIZON_OFFSET,
       AUDIO_VOICE_STATUS_OFF_HORIZON);
PARITY(off_read, ZZ9K_VOICE_STATUS_READ_CURSOR_OFFSET,
       AUDIO_VOICE_STATUS_OFF_READ);
PARITY(off_state, ZZ9K_VOICE_STATUS_STATE_OFFSET, AUDIO_VOICE_STATUS_OFF_STATE);
PARITY(off_late, ZZ9K_VOICE_STATUS_LATE_OFFSET, AUDIO_VOICE_STATUS_OFF_LATE);
PARITY(off_rejected, ZZ9K_VOICE_STATUS_REJECTED_OFFSET,
       AUDIO_VOICE_STATUS_OFF_REJECTED);
