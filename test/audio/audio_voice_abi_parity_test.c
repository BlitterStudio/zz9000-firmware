PARITY(feat_limiter, ZZ9K_VOICE_FEATURE_LIMITER, AUDIO_VOICE_FEATURE_LIMITER);
PARITY(feat_cubic, ZZ9K_VOICE_FEATURE_CUBIC, AUDIO_VOICE_FEATURE_CUBIC);
PARITY(feat_voice_interp, ZZ9K_VOICE_FEATURE_VOICE_INTERP,
       AUDIO_VOICE_FEATURE_VOICE_INTERP);
PARITY(feat_oversample, ZZ9K_VOICE_FEATURE_OVERSAMPLE,
       AUDIO_VOICE_FEATURE_OVERSAMPLE);
PARITY(feat_envelope, ZZ9K_VOICE_FEATURE_ENVELOPE, AUDIO_VOICE_FEATURE_ENVELOPE);
PARITY(feat_events, ZZ9K_VOICE_FEATURE_EVENTS, AUDIO_VOICE_FEATURE_EVENTS);
PARITY(feat_config, ZZ9K_VOICE_FEATURE_CONFIG, AUDIO_VOICE_FEATURE_CONFIG);

/* The advertised features are bits the SDK names. */
PARITY(features_known,
       AUDIO_VOICE_FEATURES & ~(ZZ9K_VOICE_FEATURE_RAMP |
                                ZZ9K_VOICE_FEATURE_LIMITER |
                                ZZ9K_VOICE_FEATURE_CUBIC |
                                ZZ9K_VOICE_FEATURE_VOICE_INTERP |
                                ZZ9K_VOICE_FEATURE_OVERSAMPLE |
                                ZZ9K_VOICE_FEATURE_ENVELOPE |
                                ZZ9K_VOICE_FEATURE_EVENTS |
                                ZZ9K_VOICE_FEATURE_CONFIG), 0U);

int main(void)
{
	printf("audio_voice_abi_parity_test: SDK and firmware voice constants "
	       "agree\n");
	return 0;
}
